"""
provenance.py — every scheme line carries where it came from and how old it is.

The Data & Accuracy rule for this product is simple: a government scheme figure
is only allowed to appear if it can be traced to a source and a date. The curated
dataset already stores ``source_url`` and ``last_verified_at`` per scheme; this
module turns those two fields into a *reviewable* claim:

    as_of       — when we last read the source
    next_review — when we promised to read it again
    due / stale — whether that promise is still good
    source_host — the official domain, shown so a user can judge it at a glance

Nothing here is generated by a model, and nothing here needs the network. A
link-health job (``backend/jobs/verify_sources.py``) may *refresh* the dates, but
the arithmetic that flags a stale record is pure and unit-tested, so a scheme can
never quietly become "verified" just because a job failed to run.
"""
from __future__ import annotations

import logging
from datetime import datetime, timedelta, timezone
from typing import Any, Dict, Optional
from urllib.parse import urlparse

logger = logging.getLogger(__name__)

# How long a curated scheme record may go unreviewed before we stop implying it
# is current. 90 days is deliberately short: scheme ceilings and subsidy rates
# move on Budget day far more often than they move on their own.
REVIEW_CADENCE_DAYS = 90

# At this many days before the review date we begin warning the operator.
REVIEW_WARN_DAYS = 14


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _parse_date(value: Any) -> Optional[datetime]:
    """Parse a curated date string. Returns None on anything unparseable.

    Accepts ``YYYY-MM-DD`` (the format used in schemes.json) and a full ISO
    timestamp. Being strict is the point: a date we cannot read is a date we
    cannot vouch for, so it is treated as missing rather than guessed.
    """
    if not value:
        return None
    if isinstance(value, datetime):
        return value if value.tzinfo else value.replace(tzinfo=timezone.utc)
    text = str(value).strip()
    for fmt in ("%Y-%m-%d", "%Y/%m/%d"):
        try:
            return datetime.strptime(text, fmt).replace(tzinfo=timezone.utc)
        except ValueError:
            continue
    try:
        parsed = datetime.fromisoformat(text.replace("Z", "+00:00"))
        return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)
    except ValueError:
        logger.debug("[provenance] unparseable date %r", value)
        return None


def source_host(url: str) -> str:
    """The bare official domain of a source, for display. Empty when absent."""
    if not url:
        return ""
    try:
        host = urlparse(url).netloc.lower()
        return host[4:] if host.startswith("www.") else host
    except Exception:  # noqa: BLE001 - never let a bad URL crash a report
        return ""


def review_dates(
    last_verified_at: Any,
    *,
    now: Optional[datetime] = None,
    cadence_days: int = REVIEW_CADENCE_DAYS,
    warn_days: int = REVIEW_WARN_DAYS,
) -> Dict[str, Any]:
    """Deterministic freshness arithmetic for one record.

    Returns a dict with ISO dates and a coarse ``freshness`` bucket:

        fresh    — comfortably inside the review window
        due_soon — review date is within ``warn_days``
        stale    — the review date has passed
        unknown  — no readable ``last_verified_at``
    """
    current = now or _now()
    verified = _parse_date(last_verified_at)
    if verified is None:
        return {
            "as_of": "",
            "next_review": "",
            "days_left": None,
            "is_stale": True,
            "due_soon": False,
            "freshness": "unknown",
            "cadence_days": cadence_days,
        }

    next_review = verified + timedelta(days=cadence_days)
    days_left = (next_review - current).days
    is_stale = days_left < 0
    due_soon = not is_stale and days_left <= warn_days
    bucket = "stale" if is_stale else ("due_soon" if due_soon else "fresh")

    return {
        "as_of": verified.date().isoformat(),
        "next_review": next_review.date().isoformat(),
        "days_left": days_left,
        "is_stale": is_stale,
        "due_soon": due_soon,
        "freshness": bucket,
        "cadence_days": cadence_days,
    }


def provenance_block(scheme: Dict[str, Any], *, now: Optional[datetime] = None) -> Dict[str, Any]:
    """The provenance block the UI renders next to a scheme.

    Kept deliberately small: a source a user can open, the date we read it, and
    whether that date is still inside the review window. A missing source URL is
    reported as ``unsourced`` rather than silently rendered as verified.
    """
    url = (scheme.get("source_url") or "").strip()
    freshness = review_dates(scheme.get("last_verified_at"), now=now)
    return {
        "source_url": url,
        "source_host": source_host(url),
        "has_source": bool(url),
        "verified": freshness["as_of"],
        "next_review": freshness["next_review"],
        "days_left": freshness["days_left"],
        "freshness": freshness["freshness"],
        "is_stale": freshness["is_stale"],
        "due_soon": freshness["due_soon"],
        "label": _label(freshness, bool(url)),
    }


def _label(freshness: Dict[str, Any], has_source: bool) -> str:
    if not has_source:
        return "unsourced"
    bucket = freshness["freshness"]
    if bucket == "unknown":
        return "review date unknown"
    if bucket == "stale":
        days = abs(freshness.get("days_left") or 0)
        return f"review due ({days}d overdue)"
    if bucket == "due_soon":
        return f"review due in {freshness.get('days_left')}d"
    return f"verified {freshness['as_of']}"


def annotate_schemes(
    schemes: list, *, now: Optional[datetime] = None
) -> list:
    """Return a copy of each scheme with a ``provenance`` block attached.

    Additive: every existing key is preserved so ``load_schemes()`` consumers keep
    working, and the endpoint gains the freshness fields for free.
    """
    annotated = []
    for scheme in schemes:
        if not isinstance(scheme, dict):
            continue
        enriched = dict(scheme)
        enriched["provenance"] = provenance_block(scheme, now=now)
        annotated.append(enriched)
    return annotated


def staleness_report(schemes: list, *, now: Optional[datetime] = None) -> Dict[str, Any]:
    """A whole-dataset health summary — what an operator looks at on a Monday.

    Also returns the ids that need attention, so the verification job (or a
    human) has a concrete worklist instead of a percentage.
    """
    stale: list = []
    due_soon: list = []
    unsourced: list = []
    unknown: list = []

    for scheme in schemes:
        if not isinstance(scheme, dict):
            continue
        sid = scheme.get("id", "")
        block = provenance_block(scheme, now=now)
        if not block["has_source"]:
            unsourced.append(sid)
        elif block["freshness"] == "unknown":
            unknown.append(sid)
        elif block["is_stale"]:
            stale.append(sid)
        elif block["due_soon"]:
            due_soon.append(sid)

    return {
        "total": len(schemes),
        "fresh": len(schemes) - len(stale) - len(due_soon) - len(unsourced) - len(unknown),
        "stale": stale,
        "due_soon": due_soon,
        "unsourced": unsourced,
        "unknown": unknown,
        "cadence_days": REVIEW_CADENCE_DAYS,
        "generated_at": (now or _now()).isoformat(),
    }
