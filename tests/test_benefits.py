"""
tests/test_benefits.py — the deterministic benefit / subsidy calculator (WS-3).

Pins the numbers a user could be told they will receive. These are exactly the
claims that must never be generated by a model, so every assertion here is a
published rule transcribed into `schemes.json` (`benefit_rules`) and computed in
pure Python:

* PMEGP margin money — 15%/25% (general) and 25%/35% (special), on a project cost
  capped at ₹50 lakh manufacturing / ₹20 lakh service;
* MUDRA tiers — Shishu ≤ ₹50,000, Kishore ₹50,001–₹5,00,000, Tarun
  ₹5,00,001–₹10,00,000, Tarun Plus ₹10,00,001–₹20,00,000;
* PM SVANidhi — ₹15,000 → ₹25,000 → ₹50,000 tranches.

Every response must also carry the disclaimer, in both languages.
"""
import pytest

from backend.core.benefits import DISCLAIMER, compute_benefits, format_inr

MANUFACTURER = {
    "business": "I make and sell candles in my home workshop",
    "offering": "decorative candles",
}
SERVICE = {"business": "I run a mobile repair service shop", "offering": "phone repair"}
VENDOR = {
    "business": "Street vendor / cart",
    "offering": "vegetables",
    "registered": "Yes, registered",
}


def _row(result, scheme_id):
    for row in result["rows"]:
        if row["scheme_id"] == scheme_id:
            return row
    return None


def _lines(result, scheme_id):
    row = _row(result, scheme_id)
    return " ".join(row["lines"]) if row else ""


# ── formatting ────────────────────────────────────────────────────────────────


def test_format_inr_uses_indian_grouping():
    assert format_inr(50000) == "₹50,000"
    assert format_inr(250000) == "₹2,50,000"
    assert format_inr(2000000) == "₹20,00,000"
    assert format_inr(11000000) == "₹1,10,00,000"
    assert format_inr(None) == "—"


# ── PMEGP ─────────────────────────────────────────────────────────────────────


def test_pmegp_subdisy_math_for_manufacturing():
    result = compute_benefits(MANUFACTURER, "", amount=300000, project_cost=1000000)
    row = _row(result, "pmegp")
    assert row is not None and row["status"] == "eligible"
    # General 15% urban / 25% rural; special 25% urban / 35% rural, on ₹10 lakh.
    assert row["subsidy_min"] == 150000
    assert row["subsidy_max"] == 350000
    assert row["own_contribution_min"] == 50000  # 5% special
    assert row["own_contribution_max"] == 100000  # 10% general
    assert result["headline"]["subsidy_min"] == 150000
    assert result["headline"]["subsidy_max"] == 350000
    text = " ".join(row["lines"])
    assert "15% urban = ₹1,50,000" in text
    assert "35% rural = ₹3,50,000" in text


def test_pmegp_service_project_is_capped_at_20_lakh():
    """A ₹30 lakh service project only earns subsidy on ₹20 lakh."""
    result = compute_benefits(SERVICE, "", amount=None, project_cost=3000000)
    row = _row(result, "pmegp")
    assert result["pmegp_sector"] == "service"
    assert row["subsidy_min"] == 300000  # 15% of the ₹20 lakh ceiling
    assert row["subsidy_max"] == 700000  # 35% of the ₹20 lakh ceiling
    assert "20,00,000" in " ".join(row["lines"])


def test_pmegp_without_project_cost_publishes_rates_only():
    result = compute_benefits(MANUFACTURER, "", amount=None, project_cost=None)
    row = _row(result, "pmegp")
    if row is None:  # no match at all is also honest
        pytest.skip("profile did not match PMEGP")
    assert row["subsidy_min"] is None and row["subsidy_max"] is None
    text = " ".join(row["lines"])
    assert "15% urban" in text and "35% rural" in text


def test_pmegp_special_category_terms_are_named():
    text = _lines(compute_benefits(MANUFACTURER, "", 300000, 1000000), "pmegp")
    for term in ("SC/ST", "OBC", "women", "transgender"):
        assert term in text


# ── MUDRA ─────────────────────────────────────────────────────────────────────


@pytest.mark.parametrize(
    "amount,expected",
    [
        (50000, "mudra-shishu"),
        (50001, "mudra-kishore"),
        (500000, "mudra-kishore"),
        (500001, "mudra-tarun"),
        (1000000, "mudra-tarun"),
        (1000001, "mudra-tarun-plus"),
    ],
)
def test_mudra_tier_follows_published_bands(amount, expected):
    result = compute_benefits(SERVICE, "", amount=amount, lang="en")
    matches = [r for r in result["rows"] if r["tier_group"] == "mudra"]
    assert len(matches) == 1, "MUDRA must collapse into one card, not four"
    assert matches[0]["scheme_id"] == expected


def test_mudra_card_prints_the_full_ladder_and_is_not_a_subsidy():
    result = compute_benefits(SERVICE, "", amount=300000)
    row = next(r for r in result["rows"] if r["tier_group"] == "mudra")
    text = " ".join(row["lines"])
    assert "₹50,001 – ₹5,00,000" in text
    assert "Tarun Plus ₹10,00,001 – ₹20,00,000" in text
    assert "No subsidy" in text
    assert row["subsidy_min"] is None
    assert row["loan_max"] == 500000  # the tier that actually fits


def test_mudra_dataset_bands_match_published_tiers():
    """The band fields must agree with the ceiling text in the same record."""
    from backend.core.heuristics import load_schemes

    bands = {s["id"]: (s.get("min_amount"), s.get("max_amount")) for s in load_schemes()}
    assert bands["mudra-shishu"] == (None, 50000)
    assert bands["mudra-kishore"] == (50001, 500000)
    assert bands["mudra-tarun"] == (500001, 1000000)
    assert bands["mudra-tarun-plus"] == (1000001, 2000000)


# ── PM SVANidhi ───────────────────────────────────────────────────────────────


def test_svanidhi_tranche_ladder():
    result = compute_benefits(VENDOR, "", amount=None)
    row = _row(result, "pm-svanidhi")
    assert row is not None
    text = " ".join(row["lines"])
    assert "₹15,000" in text and "₹25,000" in text and "₹50,000" in text
    assert row["loan_min"] == 15000
    assert row["loan_max"] == 50000


def test_svanidhi_is_never_reported_as_free_money():
    row = _row(compute_benefits(VENDOR, "", None), "pm-svanidhi")
    assert row["subsidy_min"] is None and row["subsidy_max"] is None


# ── scope, honesty, language ──────────────────────────────────────────────────


def test_a_street_vendor_is_not_quoted_a_pmegp_subsidy():
    """
    Trading and vending are outside PMEGP except in narrow cases — quoting a
    subsidy there would send a vendor to a bank counter to be turned away.
    """
    result = compute_benefits(VENDOR, "", amount=20000, project_cost=200000)
    assert _row(result, "pmegp") is None
    assert result["headline"]["subsidy_min"] in (None, 0)


def test_every_response_carries_the_disclaimer():
    for lang, marker in (("en", "Estimated from the scheme's published rules"), ("hi", "अनुमान")):
        result = compute_benefits(MANUFACTURER, "", 300000, 1000000, lang)
        assert result["disclaimer"] == DISCLAIMER[lang]
        assert marker in result["disclaimer"]


def test_hindi_lines_are_translated_but_official_terms_survive():
    result = compute_benefits(MANUFACTURER, "", 300000, 1000000, "hi")
    text = " ".join(" ".join(r["lines"]) for r in result["rows"])
    assert any("\u0900" <= ch <= "\u097f" for ch in text), "Hindi output must be Devanagari"
    assert "MUDRA" in text  # official term, never translated
    assert "à¤" not in text, "mojibake must never ship"


def test_calculation_is_deterministic_and_offline():
    first = compute_benefits(MANUFACTURER, "", 300000, 1000000)
    second = compute_benefits(MANUFACTURER, "", 300000, 1000000)
    assert first == second


# ── endpoint ──────────────────────────────────────────────────────────────────


@pytest.fixture(scope="module")
def client():
    from fastapi.testclient import TestClient

    from backend.main import app

    with TestClient(app) as c:
        yield c


def test_endpoint_answers_with_a_disclaimer(client):
    response = client.post(
        "/api/benefits",
        json={
            "intake": MANUFACTURER,
            "project_cost": 1000000,
            "amount": 300000,
            "lang": "en",
        },
    )
    assert response.status_code == 200
    body = response.json()
    assert body["disclaimer"]
    assert body["headline"]["subsidy_max"] == 350000


def test_endpoint_rejects_nonsense_input(client):
    response = client.post("/api/benefits", json={"project_cost": 10})
    assert response.status_code == 422
    response = client.post("/api/benefits", json={"project_cost": 10 ** 12})
    assert response.status_code == 422
